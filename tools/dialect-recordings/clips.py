def cues(pdftxt, greek):
    raw = parse(pdftxt); lines = greek.split("\n")
    assert len(raw) == len(lines), (pdftxt, len(raw), len(lines))
    return [{"t": c["t"], "d": c["d"], "el": g, "tr": c["tr"], "en": re.sub(r"\s{2,}", " ", c["en"]).strip()} for c, g in zip(raw, lines)]

